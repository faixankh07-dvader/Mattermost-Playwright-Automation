"""Build docs/traceability.md from the `tc` markers on the automated tests.

Run from the repository root, with the same .env the test suite uses
(conftest.py reads it at import time):

    python scripts/traceability.py

The manual test case list lives in docs/manual_cases.csv (id, epic, title).
Every manual case appears in the output, automated or not.
"""
import contextlib
import csv
import io
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
CASES_CSV = ROOT / "docs" / "manual_cases.csv"
OUTPUT = ROOT / "docs" / "traceability.md"

# Short remarks that belong next to a case. Keep them factual.
NOTES = {
    "MMQA-T16": "The browser back-button step is a manual check. The automated test asserts that the old session returns 401 and that a protected URL in a fresh tab redirects to login.",
    "MMQA-T30": "REST-level check (adding a member, changing settings of another team). Team switcher and direct-URL steps are not covered.",
    "MMQA-T45": "Server rejects the post (403) and the channel disappears from the sidebar after a refresh. The Browse Channels search step is not covered.",
    "MMQA-T49": "3 of 4 example inputs automated (script tag, raw HTML, markdown). The emoji example is not.",
    "MMQA-T9": "Not automated: changes a server-wide setting.",
    "MMQA-T14": "Not automated: locks the account and would break later tests.",
    "MMQA-T19": "Not automated: depends on email delivery.",
    "MMQA-T20": "Not automated: depends on email delivery.",
    "MMQA-T25": "Not automated: changes a server-wide setting.",
    "MMQA-T53": "Not automated: a network interruption is flaky by design.",
}


class Collector:
    def __init__(self):
        self.items = []

    def pytest_collection_modifyitems(self, items):
        self.items = list(items)


def collect_tests():
    collector = Collector()
    args = [
        "--collect-only",
        "-q",
        "-p", "no:cacheprovider",
        "-c", str(ROOT / "pytest.ini"),
        "--rootdir", str(ROOT),
        str(ROOT / "tests"),
    ]
    buffer = io.StringIO()
    with contextlib.redirect_stdout(buffer):
        exit_code = pytest.main(args, plugins=[collector])
    if exit_code != 0:
        print(buffer.getvalue())
        sys.exit(f"pytest could not collect the tests (exit code {int(exit_code)}). Is .env present?")
    return collector.items


def case_number(case_id: str) -> int:
    return int(re.sub(r"\D", "", case_id))


def level(kinds: set) -> str:
    return " + ".join(sorted(kinds))


def main():
    with CASES_CSV.open(newline="", encoding="utf-8") as fh:
        cases = {row["id"]: row for row in csv.DictReader(fh)}

    items = collect_tests()
    by_case = defaultdict(list)  # case id -> [(test function path, kind)]
    for item in items:
        kind = "API" if item.nodeid.startswith("tests/api") else "UI"
        for mark in item.iter_markers(name="tc"):
            by_case[mark.args[0]].append((item.nodeid, kind))

    unknown = sorted(set(by_case) - set(cases))
    if unknown:
        sys.exit(f"Markers refer to cases missing from {CASES_CSV.name}: {', '.join(unknown)}")

    kinds_total = Counter("API" if i.nodeid.startswith("tests/api") else "UI" for i in items)
    automated = sorted(by_case, key=case_number)

    lines = [
        "# Traceability: manual test cases to automated tests",
        "",
        "Generated by `python scripts/traceability.py` from the `tc` markers in `tests/`. Do not edit by hand.",
        "",
        f"**{len(automated)} of {len(cases)}** manual test cases are automated, by **{len(items)}** pytest tests "
        f"({kinds_total['UI']} UI, {kinds_total['API']} API). "
        "A parametrized test counts once per parameter.",
        "",
        "| Case | Epic | Title | Status | Level | Automated test(s) | Notes |",
        "|---|---|---|---|---|---|---|",
    ]

    for case_id in sorted(cases, key=case_number):
        row = cases[case_id]
        title = row["title"].replace("|", "/")
        if case_id in by_case:
            per_function = Counter(node.split("[")[0] for node, _ in by_case[case_id])
            tests = "<br>".join(
                f"`{name}`" + (f" ({count} cases)" if count > 1 else "")
                for name, count in sorted(per_function.items())
            )
            status = "Automated"
            kinds = level({kind for _, kind in by_case[case_id]})
        else:
            tests, status, kinds = "", "Not automated", ""
        lines.append(
            f"| {case_id.replace('MMQA-', '')} | {row['epic']} | {title} | {status} | {kinds} | {tests} | {NOTES.get(case_id, '')} |"
        )

    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}: {len(automated)} of {len(cases)} cases automated, {len(items)} tests.")


if __name__ == "__main__":
    main()
